package com.template.auth.academic;

import jakarta.annotation.PostConstruct;
import org.springframework.context.annotation.DependsOn;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.security.core.Authentication;
import org.springframework.web.server.ResponseStatusException;
import org.springframework.http.HttpStatus;
import java.net.URI;
import java.util.*;

@Component
@DependsOn("entityManagerFactory")
public class AcademicDb {
    final JdbcTemplate db;
    public AcademicDb(JdbcTemplate db) { this.db=db; }
    @PostConstruct void init() {
        db.execute("""
          create table if not exists academic_activity (
            id bigint generated by default as identity primary key,
            owner_id bigint not null references usuario(id) on delete cascade,
            day date not null, kind varchar(40) not null, course varchar(200) not null,
            description text not null, color varchar(7) not null)
          """);
        db.execute("""
          create table if not exists academic_meeting (
            id bigint generated by default as identity primary key,
            owner_id bigint not null references usuario(id) on delete cascade,
            title varchar(200) not null, course varchar(200) not null, description text not null,
            platform varchar(20) not null, url text not null, starts timestamp with time zone not null,
            ends timestamp with time zone not null, is_public boolean not null default false)
          """);
        db.execute("""
          create table if not exists academic_invitation (
            meeting_id bigint not null references academic_meeting(id) on delete cascade,
            user_id bigint not null references usuario(id) on delete cascade,
            status varchar(12) not null default 'PENDING', primary key(meeting_id,user_id))
          """);
        db.execute("""
          create table if not exists academic_project (
            id bigint generated by default as identity primary key,
            owner_id bigint not null references usuario(id) on delete cascade,
            title varchar(200) not null, description text not null, career varchar(150) not null,
            course varchar(150) not null, kind varchar(80) not null, members text not null,
            tags text not null, links text not null, requirements text not null,
            created timestamp with time zone not null default now())
          """);
        db.execute("""
          create table if not exists academic_file (
            id bigint generated by default as identity primary key,
            project_id bigint not null references academic_project(id) on delete cascade,
            name varchar(255) not null, storage_key varchar(80) not null unique,
            bytes bigint not null, is_main boolean not null default false, is_cover boolean not null default false)
          """);
        db.execute("create unique index if not exists academic_file_main on academic_file(project_id) where is_main");
        db.execute("create unique index if not exists academic_file_cover on academic_file(project_id) where is_cover");
        db.execute("create index if not exists academic_activity_owner_day on academic_activity(owner_id,day)");
        db.execute("create index if not exists academic_project_owner on academic_project(owner_id)");
        db.execute("create index if not exists academic_invitation_user on academic_invitation(user_id)");
    }
    long user(Authentication a) {return db.query("select id from usuario where email=?",(r,n)->r.getLong(1),a.getName()).stream().findFirst().orElseThrow(()->new ResponseStatusException(HttpStatus.UNAUTHORIZED));}
    Map<String,Object> one(String sql,Object... args){return db.queryForList(sql,args).stream().findFirst().orElseThrow(()->new ResponseStatusException(HttpStatus.NOT_FOUND,"No encontrado"));}
    void changed(int n){if(n==0)throw new ResponseStatusException(HttpStatus.NOT_FOUND,"No encontrado o sin permiso");}
    static ResponseStatusException bad(String s){return new ResponseStatusException(HttpStatus.BAD_REQUEST,s);}
    static String str(String s,int max,boolean required){s=s==null?"":s.strip();if(s.length()>max||(required&&s.isBlank()))throw bad("Revisa los campos obligatorios y su longitud");return s;}
    static URI https(String s){try{URI u=URI.create(str(s,2048,true));if(!"https".equalsIgnoreCase(u.getScheme())||u.getHost()==null||u.getUserInfo()!=null||u.getPort()!=-1&&u.getPort()!=443)throw bad("Usa un enlace HTTPS válido");return u;}catch(IllegalArgumentException e){throw bad("Enlace inválido");}}
}
